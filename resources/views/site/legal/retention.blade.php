<p>This policy explains how long QRONEX keeps data and how it is deleted. It applies alongside the <a href="{{ route('legal', 'privacy') }}">Privacy Policy</a>.</p>

<h2>1. Attendance records</h2>
<p>Attendance events, rejected punches and corrections are kept for 24 months by default. Each company's administrator can change this in the portal (Attendance policy → Record retention) to anything between 6 and 120 months. Records older than the chosen period are deleted automatically, and each deletion run is recorded in the company's audit log.</p>

<h2>2. Trial and closed accounts</h2>
<p>Trial data of companies that do not move to a paid plan may be deleted 14 days after the trial ends. When a paid account is closed, attendance data is deleted according to the employer's instructions, service termination and legal obligations. Export what you need (CSV reports or API) before closing.</p>

<h2>3. Billing and tax records</h2>
<p>Invoices, credit notes and payment records are retained for 8 years as required by Indian tax law, even after an account is closed.</p>

<h2>4. Backups</h2>
<p>Deleted data can remain in backups until those backups expire in their normal rotation; backups are used only to restore the service.</p>

<h2>5. Requests</h2>
<p>To request deletion or an export, the company administrator can write to support@ametecsindia.com. Employees should contact their employer's administrator first.</p>
